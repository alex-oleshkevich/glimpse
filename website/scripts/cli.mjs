import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const website = join(dirname(fileURLToPath(import.meta.url)), "..");
const [binDir, ...binaries] = process.argv.slice(2);
if (!binDir || binaries.length === 0) {
  console.error("usage: cli.mjs <bin-dir> <binary>...");
  process.exit(2);
}

const help = (binary, path, flag = "--help") =>
  execFileSync(join(binDir, binary), [...path, flag], {
    encoding: "utf8",
    env: { PATH: process.env.PATH, HOME: "/home/user", NO_COLOR: "1", COLUMNS: "100", LANGUAGE: "en", LC_ALL: "C" },
  });

const parse = (text) => {
  const usage = text.indexOf("Usage:");
  const about = text.slice(0, usage).trim();
  const body = text.slice(usage).trimEnd();
  const commands = [];
  const section = body.match(/^Commands:\n((?: {2}.*\n?)+)/m);
  if (section) {
    for (const line of section[1].split("\n")) {
      const name = line.match(/^ {2}(\S+)/)?.[1];
      if (name && name !== "help") commands.push(name);
    }
  }
  return { about, body, commands };
};

const render = (binary) => {
  const out = [
    "<!-- Generated by `just docs-gen-cli` from the binary's --help. Do not edit. -->",
    "",
  ];
  const globals = new Set();
  const walk = (path) => {
    const { about, commands } = parse(help(binary, path));
    let { body } = parse(help(binary, path, "-h"));
    if (path.length === 0) {
      for (const line of body.split("\n")) {
        const flag = line.match(/^ {2}(?:-\w, )? *(--[\w-]+)/)?.[1];
        if (flag && flag !== "--help") globals.add(flag);
      }
    } else {
      body = body
        .split("\n")
        .filter((line) => !globals.has(line.match(/^ {2}(?:-\w, )? *(--[\w-]+)/)?.[1]))
        .join("\n");
    }
    const title = [binary, ...path].join(" ");
    const level = path.length === 0 ? "#" : path.length === 1 ? "##" : "###";
    out.push(`${level} ${path.length === 0 ? title : `\`${title}\``}`, "");
    if (about) out.push(about, "");
    out.push("```text", body, "```", "");
    if (path.length === 0 && commands.length > 0) {
      out.push("The options above work with every command and are not repeated below.", "");
    }
    for (const command of commands) walk([...path, command]);
  };
  walk([]);
  return `${out.join("\n").trimEnd()}\n`;
};

for (const binary of binaries) {
  writeFileSync(join(website, "config", "cli", `${binary}.md`), render(binary));
}
